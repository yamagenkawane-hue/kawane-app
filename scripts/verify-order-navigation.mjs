import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const context={exports:{},URLSearchParams};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/orderProcessNavigation.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,context);
const {orderProcessesHref,findRequestedOrder}=context.exports;
let passed=0;
const check=(a,b)=>{assert.deepEqual(a,b);passed++;};
const orders=[{id:'first',orderNo:'A-001'},{id:'target',orderNo:'B & #2/川根'},{id:'same-number',orderNo:'B & #2/川根'}];
const href=orderProcessesHref('target','B & #2/川根');
const params=new URL(href,'https://example.invalid').searchParams;
check(params.get('postId'),'target');check(params.get('orderNo'),'B & #2/川根');
check(findRequestedOrder(orders,params.get('postId'),params.get('orderNo')).id,'target');
check(findRequestedOrder(orders,'same-number','B & #2/川根').id,'same-number');
check(findRequestedOrder(orders,'','A-001').id,'first');
check(findRequestedOrder(orders,'missing','A-001'),undefined);
check(findRequestedOrder(orders,'','missing'),undefined);
check(findRequestedOrder(orders,'',''),undefined);
check(orderProcessesHref('',''),'/orderProcesses');
check(new URL(orderProcessesHref('','A-001'),'https://example.invalid').searchParams.get('orderNo'),'A-001');
const many=Array.from({length:1100},(_,i)=>({id:`p${i}`,orderNo:`ORDER-${i}`}));
check(findRequestedOrder(many,'p1099','ORDER-1099').id,'p1099');
console.log(JSON.stringify({mode:'order context encoding and identity selection',passed}));
